/**
 * Utility for consolidating duplicate line items when merging Purchase Requisitions
 * into RFQs (Request for Quotations) or Purchase Orders (POs).
 *
 * When multiple requisitions contain identical items (by itemCode or itemName),
 * they are merged into a single line item with accumulated quantity, avoiding
 * redundant duplicate lines.
 */

export interface ConsolidatableItem {
  id?: string | number;
  itemCode?: string;
  itemName?: string;
  itemClass?: string;
  category?: string;
  description?: string;
  quantity?: number | string;
  unit?: string;
  expectedDate?: string;
  unitPrice?: number | string;
  totalPrice?: number;
  taxPercent?: number;
  preferredSupplierId?: string;
  preferredSupplierName?: string;
  sourcePrNumber?: string;
  sourcePrId?: string;
  sourcePrNumbers?: string[];
  sourceRequisitionIds?: string[];
  [key: string]: any;
}

/**
 * Checks whether an itemCode appears to be a generic placeholder
 * (e.g. empty, "ITEM", "ITEM-001", "item-1234") rather than an actual SKU / inventory code.
 */
export function isAutoGeneratedItemCode(code?: string): boolean {
  if (!code) return true;
  const trimmed = code.trim();
  if (!trimmed) return true;
  if (/^item(-\d+)?$/i.test(trimmed)) return true;
  return false;
}

/**
 * Determines whether two items represent the same product/catalog item.
 */
export function isSameConsolidatedItem(
  a: ConsolidatableItem,
  b: ConsolidatableItem
): boolean {
  const codeA = (a.itemCode || '').trim();
  const codeB = (b.itemCode || '').trim();
  const nameA = (a.itemName || a.description || '').trim();
  const nameB = (b.itemName || b.description || '').trim();

  const explicitCodeA = !isAutoGeneratedItemCode(codeA);
  const explicitCodeB = !isAutoGeneratedItemCode(codeB);

  // If both have explicit SKU/codes
  if (explicitCodeA && explicitCodeB) {
    return codeA.toLowerCase() === codeB.toLowerCase();
  }

  // If names match (case-insensitive)
  if (nameA && nameB && nameA.toLowerCase() === nameB.toLowerCase()) {
    // If one or both have explicit codes, check they do not conflict
    if (explicitCodeA && explicitCodeB) {
      return codeA.toLowerCase() === codeB.toLowerCase();
    }
    return true;
  }

  // If neither has a name, check if codes match
  if (!nameA && !nameB && codeA && codeB) {
    return codeA.toLowerCase() === codeB.toLowerCase();
  }

  return false;
}

/**
 * Consolidates a list of items: identical items are merged into a single entry
 * with summed quantities, combined source PR tracking, and merged descriptions.
 */
export function consolidateLineItems<T extends ConsolidatableItem>(items: T[]): T[] {
  if (!Array.isArray(items) || items.length === 0) return [];

  const result: T[] = [];

  for (const item of items) {
    const existingIndex = result.findIndex((existing) =>
      isSameConsolidatedItem(existing, item)
    );

    const incomingQty = Number(item.quantity) || 0;

    if (existingIndex >= 0) {
      const existing = result[existingIndex];
      const existingQty = Number(existing.quantity) || 0;
      const combinedQty = Math.round((existingQty + incomingQty) * 1000) / 1000;

      // Prefer explicit SKU over generic/auto-generated code
      const resolvedCode = !isAutoGeneratedItemCode(existing.itemCode)
        ? existing.itemCode
        : !isAutoGeneratedItemCode(item.itemCode)
        ? item.itemCode
        : existing.itemCode || item.itemCode;

      // Merge description without duplicating exact text
      const descA = (existing.description || '').trim();
      const descB = (item.description || '').trim();
      let mergedDesc = descA;
      if (!mergedDesc) {
        mergedDesc = descB;
      } else if (descB && !descA.toLowerCase().includes(descB.toLowerCase())) {
        mergedDesc = `${descA}; ${descB}`;
      }

      // Merge expected date (earliest non-empty date)
      let mergedDate = existing.expectedDate || item.expectedDate || '';
      if (existing.expectedDate && item.expectedDate && existing.expectedDate !== item.expectedDate) {
        mergedDate = existing.expectedDate < item.expectedDate ? existing.expectedDate : item.expectedDate;
      }

      // Merge source PR numbers
      const sourcePrNums = Array.from(
        new Set([
          ...(existing.sourcePrNumbers || (existing.sourcePrNumber ? [existing.sourcePrNumber] : [])),
          ...(item.sourcePrNumbers || (item.sourcePrNumber ? [item.sourcePrNumber] : [])),
        ].filter(Boolean))
      );

      // Merge source Requisition IDs
      const sourcePrIds = Array.from(
        new Set([
          ...(existing.sourceRequisitionIds || (existing.sourcePrId ? [existing.sourcePrId] : [])),
          ...(item.sourceRequisitionIds || (item.sourcePrId ? [item.sourcePrId] : [])),
        ].filter(Boolean))
      );

      // Unit price & total price (if applicable for PO)
      const existingPrice = Number(existing.unitPrice) || 0;
      const incomingPrice = Number(item.unitPrice) || 0;
      const resolvedUnitPrice = existingPrice || incomingPrice;

      result[existingIndex] = {
        ...existing,
        itemCode: resolvedCode,
        itemName: existing.itemName || item.itemName || '',
        itemClass: existing.itemClass || item.itemClass || existing.category || item.category,
        category: existing.category || item.category || existing.itemClass || item.itemClass,
        description: mergedDesc,
        quantity: typeof existing.quantity === 'string' ? String(combinedQty) : combinedQty,
        unit: existing.unit || item.unit || 'pcs',
        expectedDate: mergedDate,
        preferredSupplierId: existing.preferredSupplierId || item.preferredSupplierId,
        preferredSupplierName: existing.preferredSupplierName || item.preferredSupplierName,
        sourcePrNumber: sourcePrNums.join(', '),
        sourcePrNumbers: sourcePrNums,
        sourcePrId: sourcePrIds[0] || existing.sourcePrId || item.sourcePrId,
        sourceRequisitionIds: sourcePrIds,
        unitPrice: typeof existing.unitPrice === 'string' ? String(resolvedUnitPrice) : resolvedUnitPrice,
        totalPrice: (existing.totalPrice !== undefined || item.totalPrice !== undefined)
          ? Math.round(combinedQty * resolvedUnitPrice * 100) / 100
          : undefined,
      };
    } else {
      const parsedQty = typeof item.quantity === 'string' ? String(incomingQty) : incomingQty;
      result.push({
        ...item,
        quantity: parsedQty,
        sourcePrNumbers: item.sourcePrNumbers || (item.sourcePrNumber ? [item.sourcePrNumber] : []),
        sourceRequisitionIds: item.sourceRequisitionIds || (item.sourcePrId ? [item.sourcePrId] : []),
      });
    }
  }

  return result;
}
