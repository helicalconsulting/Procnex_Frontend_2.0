import { describe, it, expect } from 'vitest';
import { consolidateLineItems, isSameConsolidatedItem, isAutoGeneratedItemCode } from '../consolidation';

describe('consolidation utils', () => {
  it('detects auto-generated item codes', () => {
    expect(isAutoGeneratedItemCode('')).toBe(true);
    expect(isAutoGeneratedItemCode('ITEM')).toBe(true);
    expect(isAutoGeneratedItemCode('ITEM-001')).toBe(true);
    expect(isAutoGeneratedItemCode('ITEM-12')).toBe(true);
    expect(isAutoGeneratedItemCode('A-001')).toBe(false);
    expect(isAutoGeneratedItemCode('LAP-DELL-15')).toBe(false);
  });

  it('correctly matches same items by SKU or item name', () => {
    // Exact SKU match
    expect(
      isSameConsolidatedItem(
        { itemCode: 'A-001', itemName: 'Dell Laptop' },
        { itemCode: 'A-001', itemName: 'Dell Laptop' }
      )
    ).toBe(true);

    // Case-insensitive SKU match
    expect(
      isSameConsolidatedItem(
        { itemCode: 'a-001', itemName: 'Dell Laptop' },
        { itemCode: 'A-001', itemName: 'Dell Laptop' }
      )
    ).toBe(true);

    // Auto-generated code but matching itemName
    expect(
      isSameConsolidatedItem(
        { itemCode: 'ITEM-001', itemName: 'Dell Laptop' },
        { itemCode: 'ITEM-002', itemName: 'Dell Laptop' }
      )
    ).toBe(true);

    // Different SKUs should not match
    expect(
      isSameConsolidatedItem(
        { itemCode: 'A-001', itemName: 'Dell Laptop' },
        { itemCode: 'A-002', itemName: 'Dell Laptop' }
      )
    ).toBe(false);
  });

  it('consolidates items from merged PRs and sums quantities (screenshot scenario)', () => {
    const rawItems = [
      {
        id: 'item-1',
        itemCode: 'A-001',
        itemName: 'Dell Laptop',
        description: 'i7, graphic card of 4gb',
        quantity: 20,
        unit: 'pcs',
        expectedDate: '2026-09-12',
        sourcePrNumber: 'PR-001',
        sourcePrId: 'pr-1',
      },
      {
        id: 'item-2',
        itemCode: 'A-001',
        itemName: 'Dell Laptop',
        description: 'i7, graphic card of 4gb',
        quantity: 1,
        unit: 'pcs',
        expectedDate: '2026-09-12',
        sourcePrNumber: 'PR-002',
        sourcePrId: 'pr-2',
      },
    ];

    const consolidated = consolidateLineItems(rawItems);

    expect(consolidated).toHaveLength(1);
    expect(consolidated[0].itemCode).toBe('A-001');
    expect(consolidated[0].itemName).toBe('Dell Laptop');
    expect(consolidated[0].description).toBe('i7, graphic card of 4gb');
    expect(consolidated[0].quantity).toBe(21);
    expect(consolidated[0].unit).toBe('pcs');
    expect(consolidated[0].sourcePrNumber).toBe('PR-001, PR-002');
  });

  it('preserves string quantity formatting if inputs are string', () => {
    const rawItems = [
      {
        id: 'item-1',
        itemCode: 'A-001',
        itemName: 'Dell Laptop',
        quantity: '20',
      },
      {
        id: 'item-2',
        itemCode: 'A-001',
        itemName: 'Dell Laptop',
        quantity: '1',
      },
    ];

    const consolidated = consolidateLineItems(rawItems);

    expect(consolidated).toHaveLength(1);
    expect(consolidated[0].quantity).toBe('21');
  });

  it('does not merge different items', () => {
    const rawItems = [
      {
        id: 'item-1',
        itemCode: 'A-001',
        itemName: 'Dell Laptop',
        quantity: 5,
      },
      {
        id: 'item-2',
        itemCode: 'B-002',
        itemName: 'Wireless Mouse',
        quantity: 10,
      },
    ];

    const consolidated = consolidateLineItems(rawItems);

    expect(consolidated).toHaveLength(2);
    expect(consolidated[0].quantity).toBe(5);
    expect(consolidated[1].quantity).toBe(10);
  });
});
